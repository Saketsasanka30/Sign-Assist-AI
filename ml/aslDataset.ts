/**
 * Formats relevant ASL phonological dataset entries & minimal-pair rules for prompt grounding.
 */
export function buildAslDatasetContext(priorityVocabulary: string[] = []): string {
  const vocabLower = new Set(priorityVocabulary.map((v) => v.toLowerCase()));

  const prioritized = ASL_DATASET.filter(
    (entry) =>
      vocabLower.has(entry.gloss.toLowerCase()) ||
      entry.english.some((e) => vocabLower.has(e.toLowerCase()))
  );

  const coreCatalog = ASL_DATASET.filter((e) => e.category !== "alphabet")
    .map(
      (e) =>
        `${e.gloss} ("${e.english[0]}"): handshape=[${e.handshape}], location=[${e.location}], movement=[${e.movement}]${
          e.nonManual ? `, NMM=[${e.nonManual}]` : ""
        }`
    )
    .join("\n");

  const alphabetCatalog = ASL_DATASET.filter((e) => e.category === "alphabet")
    .map((e) => `${e.gloss}: ${e.handshape}`)
    .join(" | ");

  const prioritySection =
    prioritized.length > 0
      ? `\nPRIORITY CONTEXT SIGNS:\n${prioritized
          .map((e) => `${e.gloss} -> "${e.english.join('" / "')}": ${e.handshape}; ${e.movement}`)
          .join("\n")}\n`
      : "";

  return [
    "CURATED WLASL / ASL-LEX PHONOLOGICAL REFERENCE DATASET:",
    coreCatalog,
    `FINGERSPELLING REFERENCE: ${alphabetCatalog}`,
    prioritySection,
    "MINIMAL-PAIR DISAMBIGUATION RULES:",
    ASL_MINIMAL_PAIR_RULES.map((r, i) => `${i + 1}. ${r}`).join("\n"),
    "ASL GRAMMAR RULES:",
    "- Topic-Comment word order: convert gloss order (e.g., STORE I GO) into natural English ('I am going to the store.').",
    "- Non-Manual Markers: raised eyebrows indicate Yes/No questions; furrowed brows indicate WH-questions (WHAT, WHERE, WHEN, WHY, HOW, WHO); headshake negates the clause.",
    "- If the signer clearly produces fingerspelled letters, spell out the word accurately.",
  ].join("\n");
}
